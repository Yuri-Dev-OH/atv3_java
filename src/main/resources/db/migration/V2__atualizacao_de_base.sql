-- ATVIII: empresa, usuários com perfis, e-mails, credenciais, veículos, mercadorias, serviços e vendas.
-- Os clientes da ATVII viram usuários com perfil CLIENTE de uma empresa criada para recebê-los.

CREATE TABLE empresa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    razao_social VARCHAR(150) NOT NULL,
    nome_fantasia VARCHAR(150),
    cadastro TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    endereco_id BIGINT UNIQUE REFERENCES endereco(id)
);
INSERT INTO empresa (razao_social, cadastro)
    SELECT 'Empresa migrada da ATVII', CURRENT_TIMESTAMP FROM (VALUES (1)) WHERE EXISTS (SELECT 1 FROM cliente);

ALTER TABLE cliente RENAME TO usuario;
ALTER TABLE usuario ADD COLUMN empresa_id BIGINT;
UPDATE usuario SET empresa_id = (SELECT MIN(id) FROM empresa);
ALTER TABLE usuario ALTER COLUMN empresa_id SET NOT NULL;
ALTER TABLE usuario ADD CONSTRAINT fk_usuario_empresa FOREIGN KEY (empresa_id) REFERENCES empresa(id);
ALTER TABLE usuario ALTER COLUMN data_nascimento SET NULL;
CREATE INDEX ix_usuario_empresa ON usuario(empresa_id);

CREATE TABLE usuario_perfil (
    usuario_id BIGINT NOT NULL REFERENCES usuario(id),
    perfil VARCHAR(20) NOT NULL,
    PRIMARY KEY (usuario_id, perfil)
);
INSERT INTO usuario_perfil (usuario_id, perfil) SELECT id, 'CLIENTE' FROM usuario;

-- Documento: tipo passa a ser enumerado, ganha data de emissão e fica único por empresa.
DELETE FROM documento WHERE cliente_id IS NULL;
ALTER TABLE documento ALTER COLUMN cliente_id RENAME TO usuario_id;
ALTER INDEX ix_documento_cliente RENAME TO ix_documento_usuario;
ALTER TABLE documento ADD COLUMN data_emissao DATE;
ALTER TABLE documento ADD COLUMN empresa_id BIGINT;
UPDATE documento d SET empresa_id = (SELECT u.empresa_id FROM usuario u WHERE u.id = d.usuario_id);
ALTER TABLE documento ALTER COLUMN empresa_id SET NOT NULL;
ALTER TABLE documento ADD CONSTRAINT fk_documento_empresa FOREIGN KEY (empresa_id) REFERENCES empresa(id);
UPDATE documento SET tipo = UPPER(TRIM(tipo));
UPDATE documento SET tipo = 'OUTRO' WHERE tipo NOT IN ('CPF', 'CNPJ', 'RG', 'CNH', 'PASSAPORTE');
ALTER TABLE documento DROP CONSTRAINT uk_documento_numero;
ALTER TABLE documento ADD CONSTRAINT uk_documento_empresa UNIQUE (empresa_id, tipo, numero);

-- Telefone: pertence a um usuário ou a uma empresa.
ALTER TABLE telefone ALTER COLUMN cliente_id RENAME TO usuario_id;
ALTER TABLE telefone RENAME CONSTRAINT uk_telefone_cliente TO uk_telefone_usuario;
ALTER INDEX ix_telefone_cliente RENAME TO ix_telefone_usuario;
ALTER TABLE telefone ADD COLUMN empresa_id BIGINT REFERENCES empresa(id);
ALTER TABLE telefone ADD CONSTRAINT uk_telefone_empresa UNIQUE (empresa_id, ddd, numero);
CREATE INDEX ix_telefone_empresa ON telefone(empresa_id);

CREATE TABLE email (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endereco VARCHAR(254) NOT NULL,
    usuario_id BIGINT REFERENCES usuario(id),
    CONSTRAINT uk_email_usuario UNIQUE (usuario_id, endereco)
);

CREATE TABLE credencial (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    criacao TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    ultimo_acesso TIMESTAMP(6) WITH TIME ZONE,
    inativo BOOLEAN NOT NULL,
    usuario_id BIGINT REFERENCES usuario(id)
);
CREATE INDEX ix_credencial_usuario ON credencial(usuario_id);
CREATE TABLE credencial_usuario_senha (
    id BIGINT PRIMARY KEY REFERENCES credencial(id),
    nome_usuario VARCHAR(50) NOT NULL,
    senha VARCHAR(200) NOT NULL,
    CONSTRAINT uk_credencial_nome_usuario UNIQUE (nome_usuario)
);
CREATE TABLE credencial_codigo_barra (
    id BIGINT PRIMARY KEY REFERENCES credencial(id),
    codigo BIGINT NOT NULL,
    CONSTRAINT uk_credencial_codigo UNIQUE (codigo)
);

CREATE TABLE veiculo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(10) NOT NULL,
    modelo VARCHAR(100) NOT NULL,
    placa VARCHAR(7) NOT NULL,
    proprietario_id BIGINT NOT NULL REFERENCES usuario(id),
    empresa_id BIGINT NOT NULL REFERENCES empresa(id),
    CONSTRAINT uk_veiculo_placa UNIQUE (empresa_id, placa)
);
CREATE INDEX ix_veiculo_proprietario ON veiculo(proprietario_id);

CREATE TABLE mercadoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresa(id),
    fornecedor_id BIGINT REFERENCES usuario(id),
    nome VARCHAR(150) NOT NULL,
    descricao VARCHAR(255),
    fabricacao DATE,
    validade DATE,
    cadastro TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    quantidade BIGINT NOT NULL CHECK (quantidade >= 0),
    valor NUMERIC(12, 2) NOT NULL CHECK (valor >= 0)
);
CREATE INDEX ix_mercadoria_empresa ON mercadoria(empresa_id);
CREATE INDEX ix_mercadoria_fornecedor ON mercadoria(fornecedor_id);

CREATE TABLE servico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresa(id),
    nome VARCHAR(150) NOT NULL,
    descricao VARCHAR(255),
    valor NUMERIC(12, 2) NOT NULL CHECK (valor >= 0)
);
CREATE INDEX ix_servico_empresa ON servico(empresa_id);

CREATE TABLE venda (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresa(id),
    identificacao VARCHAR(50) NOT NULL,
    cadastro TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    cliente_id BIGINT NOT NULL REFERENCES usuario(id),
    funcionario_id BIGINT NOT NULL REFERENCES usuario(id),
    veiculo_id BIGINT REFERENCES veiculo(id),
    CONSTRAINT uk_venda_identificacao UNIQUE (empresa_id, identificacao)
);
CREATE INDEX ix_venda_cliente ON venda(cliente_id);
CREATE INDEX ix_venda_funcionario ON venda(funcionario_id);
CREATE INDEX ix_venda_veiculo ON venda(veiculo_id);

CREATE TABLE venda_mercadoria (
    venda_id BIGINT NOT NULL REFERENCES venda(id),
    posicao INTEGER NOT NULL,
    mercadoria_id BIGINT NOT NULL REFERENCES mercadoria(id),
    nome VARCHAR(150) NOT NULL,
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    valor_unitario NUMERIC(12, 2) NOT NULL,
    PRIMARY KEY (venda_id, posicao)
);
CREATE INDEX ix_venda_mercadoria_mercadoria ON venda_mercadoria(mercadoria_id);

CREATE TABLE venda_servico (
    venda_id BIGINT NOT NULL REFERENCES venda(id),
    posicao INTEGER NOT NULL,
    servico_id BIGINT NOT NULL REFERENCES servico(id),
    nome VARCHAR(150) NOT NULL,
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    valor_unitario NUMERIC(12, 2) NOT NULL,
    PRIMARY KEY (venda_id, posicao)
);
CREATE INDEX ix_venda_servico_servico ON venda_servico(servico_id);
